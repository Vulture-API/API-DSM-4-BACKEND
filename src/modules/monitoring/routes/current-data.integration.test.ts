import { randomUUID } from "node:crypto";

import type { FastifyInstance } from "fastify";
import { Pool } from "pg";
import {
  afterAll,
  afterEach,
  beforeAll,
  beforeEach,
  describe,
  expect,
  it,
} from "vitest";

import { buildApp } from "@/app.js";
import { hashPassword } from "@/modules/users/services/password-hasher.js";

const url = process.env.TEST_DATABASE_URL;
const schema = `it_scrum595_${randomUUID().replaceAll("-", "")}`;
const password = "scrum595-test-password";
const measuredAt = "2026-11-17T14:00:00.000Z";
const temperature = {
  sensor_id: 100,
  local_identifier: "TEMP-01",
  sensor_type_id: 1,
  sensor_type: "Temperatura",
  unit_of_measure: "°C",
  value: 25.5,
  unix_time: 1794924000,
};
const humidity = {
  sensor_id: 101,
  local_identifier: "UMID-01",
  sensor_type_id: 2,
  sensor_type: "Umidade",
  unit_of_measure: "%",
  value: 60,
  unix_time: 1794923880,
};

// SCRUM-595 / INT-US16-01: HTTP -> service -> PgMonitoringRepository -> PostgreSQL.
// SQL prepares fixtures only. Login and all queries under test use the real app.
describe.skipIf(!url)("US16: dados atuais autenticados (Postgres real)", () => {
  let pool: Pool;
  let app: FastifyInstance;
  let headers: { authorization: string };

  beforeAll(async () => {
    const setup = new Pool({ connectionString: url });
    try {
      // Same types and relationships used by BANCO; isolated from public and
      // from other integration suites. No shared migrations or seed changes.
      await setup.query(`
        CREATE SCHEMA ${schema};
        SET search_path = ${schema};
        CREATE TABLE roles (id integer PRIMARY KEY, name varchar(50) NOT NULL UNIQUE);
        CREATE TABLE users (
          id integer PRIMARY KEY, role_id integer NOT NULL REFERENCES roles(id),
          name varchar(150) NOT NULL, active boolean NOT NULL DEFAULT true,
          created_at timestamp NOT NULL DEFAULT current_timestamp
        );
        CREATE TABLE credentials (
          user_id integer PRIMARY KEY REFERENCES users(id),
          email varchar(150) NOT NULL UNIQUE, password_hash varchar(255) NOT NULL
        );
        CREATE TABLE permissions (code varchar(100) PRIMARY KEY);
        CREATE TABLE role_permissions (
          role_id integer REFERENCES roles(id),
          permission_code varchar(100) REFERENCES permissions(code),
          PRIMARY KEY(role_id, permission_code)
        );
        CREATE TABLE properties (id integer PRIMARY KEY, name varchar(150) NOT NULL);
        CREATE TABLE user_properties (
          user_id integer REFERENCES users(id), property_id integer REFERENCES properties(id),
          PRIMARY KEY(user_id, property_id)
        );
        CREATE TABLE stations (
          id integer PRIMARY KEY, property_id integer NOT NULL REFERENCES properties(id),
          name varchar(100) NOT NULL, last_communication_at timestamp
        );
        CREATE TABLE sensor_types (
          id integer PRIMARY KEY, name varchar(50) NOT NULL,
          unit_of_measure varchar(20) NOT NULL
        );
        CREATE TABLE sensors (
          id integer PRIMARY KEY, station_id integer NOT NULL REFERENCES stations(id),
          sensor_type_id integer NOT NULL REFERENCES sensor_types(id),
          local_identifier varchar(50) NOT NULL, operational_status boolean NOT NULL DEFAULT true,
          UNIQUE(station_id, local_identifier)
        );
        CREATE TABLE readings (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          sensor_id integer NOT NULL REFERENCES sensors(id), value numeric NOT NULL,
          unix_time bigint NOT NULL, data_consistent boolean NOT NULL DEFAULT true
        );
        CREATE INDEX ON readings(sensor_id, unix_time DESC);
        CREATE TABLE alert_configs (id integer PRIMARY KEY, sensor_id integer REFERENCES sensors(id));
        CREATE TABLE triggered_alerts (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          alert_config_id integer REFERENCES alert_configs(id), acknowledged_at timestamp
        );
        INSERT INTO roles VALUES (1, 'Cliente'), (2, 'Sem leitura meteorológica');
        INSERT INTO users (id, role_id, name) VALUES (1, 1, 'Cliente QA'), (2, 2, 'Sem permissão');
        INSERT INTO permissions VALUES ('monitoring.read');
        INSERT INTO role_permissions VALUES (1, 'monitoring.read');
        INSERT INTO properties VALUES (1, 'Fazenda A'), (2, 'Fazenda B');
        INSERT INTO user_properties VALUES (1, 1), (2, 1);
        INSERT INTO stations VALUES
          (10, 1, 'Estação Norte', '2026-11-17 14:09:00'),
          (11, 1, 'Estação sem leitura válida', NULL),
          (12, 1, 'Estação sem sensores', NULL),
          (20, 2, 'Estação de outro cliente', '2026-11-17 14:09:00');
        INSERT INTO sensor_types VALUES (1, 'Temperatura', '°C'), (2, 'Umidade', '%');
        INSERT INTO sensors (id, station_id, sensor_type_id, local_identifier) VALUES
          (100, 10, 1, 'TEMP-01'), (101, 10, 2, 'UMID-01'),
          (110, 11, 1, 'TEMP-02'), (111, 11, 2, 'UMID-02'), (200, 20, 1, 'TEMP-03');
      `);
      const hash = await hashPassword(password);
      await setup.query(
        `INSERT INTO ${schema}.credentials VALUES
          (1, 'cliente@example.com', $1), (2, 'sem-permissao@example.com', $1)`,
        [hash],
      );
    } finally {
      await setup.end();
    }
    pool = new Pool({
      connectionString: url,
      options: `-c search_path=${schema} -c TimeZone=America/Sao_Paulo`,
    });
  });

  beforeEach(async () => {
    await pool.query(`
      TRUNCATE readings RESTART IDENTITY;
      INSERT INTO readings (sensor_id, value, unix_time, data_consistent) VALUES
        (100, 22.0, 1794923400, true),
        (100, 25.5, 1794924000, true),
        (100, 99.0, 1794924300, false),
        (101, 60, 1794923880, true),
        (111, 99, 1794924300, false),
        (200, 18, 1794924000, true);
    `);
    app = buildApp({
      database: pool,
      accessControlEnabled: true,
      jwtSecret: "scrum595-isolated-integration-test-secret",
      clock: () => new Date("2026-11-17T14:10:00Z"),
      stationOfflineThresholdMinutes: 10,
    });
    headers = await login("cliente@example.com");
  });

  afterEach(async () => {
    await app?.close();
  });

  afterAll(async () => {
    // Use a separate connection so setup failures also clean up this schema.
    const cleanup = new Pool({ connectionString: url });
    try {
      await pool?.end();
      await cleanup.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
    } finally {
      await cleanup.end();
    }
  });

  async function login(email: string) {
    const response = await app.inject({
      method: "POST",
      url: "/api/auth/login",
      payload: { email, password },
    });
    expect(response.statusCode).toBe(200);
    return { authorization: `Bearer ${response.json().access_token}` };
  }

  it("retorna a estação e a última leitura consistente de cada sensor", async () => {
    const response = await app.inject({
      url: "/api/stations/current?station_id=10",
      headers,
    });
    expect(response.statusCode).toBe(200);
    expect(response.json()).toEqual({
      generated_at: "2026-11-17T14:10:00.000Z",
      offline_threshold_minutes: 10,
      stations: [
        {
          station_id: 10,
          name: "Estação Norte",
          property_id: 1,
          property_name: "Fazenda A",
          status: "Online",
          last_update: measuredAt,
          readings: [temperature, humidity],
        },
      ],
    });
  });

  it("lista somente estações da propriedade vinculada ao Cliente", async () => {
    const response = await app.inject({
      url: "/api/stations/current",
      headers,
    });
    expect(response.statusCode).toBe(200);
    expect(response.json().stations).toEqual([
      expect.objectContaining({
        station_id: 10,
        readings: [temperature, humidity],
      }),
      expect.objectContaining({ station_id: 11 }),
      expect.objectContaining({ station_id: 12 }),
    ]);
  });

  it("mantém sensores sem leituras consistentes com valores e atualização nulos", async () => {
    const response = await app.inject({
      url: "/api/stations/current?station_id=11",
      headers,
    });
    expect(response.statusCode).toBe(200);
    expect(response.json().stations).toEqual([
      expect.objectContaining({
        station_id: 11,
        last_update: null,
        readings: [
          expect.objectContaining({
            sensor_id: 110,
            value: null,
            unix_time: null,
          }),
          expect.objectContaining({
            sensor_id: 111,
            value: null,
            unix_time: null,
          }),
        ],
      }),
    ]);
  });

  it("retorna uma estação sem sensores com leituras vazias", async () => {
    const response = await app.inject({
      url: "/api/stations/current?station_id=12",
      headers,
    });
    expect(response.statusCode).toBe(200);
    expect(response.json().stations).toEqual([
      expect.objectContaining({
        station_id: 12,
        readings: [],
        last_update: null,
      }),
    ]);
  });

  it("retorna 404 para estação inexistente", async () => {
    const response = await app.inject({
      url: "/api/stations/current?station_id=999",
      headers,
    });
    expect(response.statusCode).toBe(404);
  });

  it("recusa consulta sem autenticação ou sem monitoring.read", async () => {
    const anonymous = await app.inject({
      url: "/api/stations/current?station_id=10",
    });
    expect(anonymous.statusCode).toBe(401);
    const unauthorized = await app.inject({
      url: "/api/stations/current?station_id=10",
      headers: await login("sem-permissao@example.com"),
    });
    expect(unauthorized.statusCode).toBe(403);
  });
});
