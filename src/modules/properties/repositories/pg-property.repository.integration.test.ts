import { Pool } from "pg";
import { afterAll, beforeAll, beforeEach, describe, expect, it } from "vitest";

import { UserReferenceNotFoundError } from "@/modules/properties/errors/property.errors.js";
import { PgPropertyRepository } from "@/modules/properties/repositories/pg-property.repository.js";

const TEST_DATABASE_URL = process.env.TEST_DATABASE_URL;
const SCHEMA = `it_properties_${process.pid}`;

describe.skipIf(!TEST_DATABASE_URL)(
  "PgPropertyRepository (Postgres real)",
  () => {
    let pool: Pool;
    let repository: PgPropertyRepository;

    beforeAll(async () => {
      const admin = new Pool({ connectionString: TEST_DATABASE_URL });
      await admin.query(`DROP SCHEMA IF EXISTS ${SCHEMA} CASCADE`);
      await admin.query(`CREATE SCHEMA ${SCHEMA}`);
      await admin.query(`
        CREATE TABLE ${SCHEMA}.users (id integer PRIMARY KEY, name varchar(100));
        INSERT INTO ${SCHEMA}.users (id, name) VALUES (1, 'Admin'), (2, 'User 2');
        CREATE TABLE ${SCHEMA}.properties (
          id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          name varchar(100) NOT NULL,
          owner_user_id integer NOT NULL REFERENCES ${SCHEMA}.users (id),
          location varchar(255) NULL,
          created_at timestamp NOT NULL DEFAULT current_timestamp
        );
      `);
      await admin.end();

      pool = new Pool({
        connectionString: TEST_DATABASE_URL,
        options: `-c search_path=${SCHEMA}`,
      });
      repository = new PgPropertyRepository(pool);
    });

    beforeEach(async () => {
      await pool.query("TRUNCATE properties RESTART IDENTITY");
    });

    afterAll(async () => {
      await pool?.query(`DROP SCHEMA IF EXISTS ${SCHEMA} CASCADE`);
      await pool?.end();
    });

    it("should_create_property_when_data_is_valid", async () => {
      const property = await repository.create({
        name: "Fazenda Real",
        owner_user_id: 1,
        location: "Taubaté - SP",
      });

      expect(property.id).toBe(1);
      expect(property.name).toBe("Fazenda Real");
      expect(property.owner_user_id).toBe(1);
      expect(property.location).toBe("Taubaté - SP");
      expect(property.created_at).toBeDefined();
    });

    it("should_find_by_id", async () => {
      const created = await repository.create({
        name: "Fazenda Sol",
        owner_user_id: 2,
        location: null,
      });

      const found = await repository.findById(created.id);
      expect(found).toMatchObject({
        id: created.id,
        name: "Fazenda Sol",
        owner_user_id: 2,
        location: null,
      });
    });

    it("should_return_null_when_not_found", async () => {
      const found = await repository.findById(999);
      expect(found).toBeNull();
    });

    it("should_check_user_exists", async () => {
      expect(await repository.userExists(1)).toBe(true);
      expect(await repository.userExists(999)).toBe(false);
    });

    it("should_rethrow_foreign_key_violation_when_user_does_not_exist", async () => {
      await expect(
        repository.create({
          name: "Fazenda Sem Dono",
          owner_user_id: 999,
        }),
      ).rejects.toBeInstanceOf(UserReferenceNotFoundError);
    });

    it("should_list_properties_ordered_by_name", async () => {
      await repository.create({ name: "Fazenda Z", owner_user_id: 1 });
      await repository.create({ name: "Fazenda A", owner_user_id: 1 });

      const list = await repository.listProperties();
      expect(list).toHaveLength(2);
      expect(list[0]?.name).toBe("Fazenda A");
      expect(list[1]?.name).toBe("Fazenda Z");
    });
  },
);
