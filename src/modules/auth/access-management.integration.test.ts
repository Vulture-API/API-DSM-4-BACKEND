import { randomUUID } from "node:crypto";

import type { FastifyInstance } from "fastify";
import { Pool } from "pg";
import {
  afterAll,
  afterEach,
  beforeAll,
  beforeEach,
  describe,
  expect,
  it,
} from "vitest";

import { buildApp } from "@/app.js";
import {
  type PermissionCode,
  PERMISSIONS,
} from "@/modules/permissions/permission-catalog.js";
import type { Role } from "@/modules/roles/types/role.type.js";
import { hashPassword } from "@/modules/users/services/password-hasher.js";
import type { User } from "@/modules/users/types/user.type.js";

const url = process.env.TEST_DATABASE_URL;
const schema = `it_scrum438_${randomUUID().replaceAll("-", "")}`;
const password = "scrum438-test-password";
type Headers = { authorization: string };

// All changes under test go through HTTP; SQL only prepares fixtures and
// independently checks persisted state. No authentication/repository mocks.
describe.skipIf(!url)(
  "SCRUM-438 access management acceptance (Postgres real)",
  () => {
    let pool: Pool;
    let app: FastifyInstance;
    let passwordHash: string;
    let admin: Headers;
    let member: Headers;
    let peer: Headers;
    let memberRole: number;
    let memberUser: User;

    beforeAll(async () => {
      passwordHash = await hashPassword(password);
      const setup = new Pool({ connectionString: url });
      try {
        await setup.query(`
        CREATE SCHEMA ${schema};
        CREATE TABLE ${schema}.roles (
          id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 10) PRIMARY KEY,
          name varchar(50) NOT NULL UNIQUE,
          description varchar(255),
          created_at timestamp NOT NULL DEFAULT current_timestamp
        );
        CREATE TABLE ${schema}.users (
          id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
          role_id integer NOT NULL REFERENCES ${schema}.roles(id) ON DELETE RESTRICT,
          name varchar(150) NOT NULL,
          active boolean NOT NULL DEFAULT true,
          created_at timestamp NOT NULL DEFAULT current_timestamp
        );
        CREATE TABLE ${schema}.credentials (
          id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id integer NOT NULL UNIQUE REFERENCES ${schema}.users(id) ON DELETE CASCADE,
          email varchar(150) NOT NULL UNIQUE,
          password_hash varchar(255) NOT NULL
        );
        CREATE TABLE ${schema}.permissions (
          code varchar(100) PRIMARY KEY, description varchar(255) NOT NULL
        );
        CREATE TABLE ${schema}.role_permissions (
          role_id integer NOT NULL REFERENCES ${schema}.roles(id) ON DELETE CASCADE,
          permission_code varchar(100) NOT NULL REFERENCES ${schema}.permissions(code) ON DELETE RESTRICT,
          PRIMARY KEY (role_id, permission_code)
        );
      `);
      } finally {
        await setup.end();
      }
      pool = new Pool({
        connectionString: url,
        options: `-c search_path=${schema}`,
      });
      await pool.query(
        "INSERT INTO permissions SELECT * FROM unnest($1::text[], $2::text[])",
        [
          PERMISSIONS.map(({ code }) => code),
          PERMISSIONS.map(({ description }) => description),
        ],
      );
    });

    beforeEach(async () => {
      await pool.query(
        "TRUNCATE credentials, users, role_permissions, roles RESTART IDENTITY",
      );
      // Deliberately use a non-admin name for the privileged role and an admin
      // name for the empty one: access must depend on grants, never labels/IDs.
      const roles = await pool.query<{ id: number }>(
        "INSERT INTO roles (name) VALUES ('Operador QA'), ('Administrador') RETURNING id",
      );
      const adminRole = roles.rows[0]!.id;
      memberRole = roles.rows[1]!.id;
      await pool.query(
        "INSERT INTO role_permissions SELECT $1, code FROM permissions",
        [adminRole],
      );
      const users = await pool.query<{ id: number }>(
        "INSERT INTO users (role_id, name) VALUES ($1, 'Admin QA'), ($2, 'Member QA'), ($2, 'Peer QA') RETURNING id",
        [adminRole, memberRole],
      );
      for (const [index, email] of [
        "admin@example.com",
        "member@example.com",
        "peer@example.com",
      ].entries()) {
        await pool.query(
          "INSERT INTO credentials (user_id, email, password_hash) VALUES ($1, $2, $3)",
          [users.rows[index]!.id, email, passwordHash],
        );
      }
      app = buildApp({
        database: pool,
        jwtSecret: "scrum438-isolated-acceptance-test-secret",
        accessControlEnabled: true,
      });
      admin = await login("admin@example.com");
      member = await login("member@example.com");
      peer = await login("peer@example.com");
      const response = await app.inject({
        url: "/api/auth/me",
        headers: member,
      });
      expect(response.statusCode).toBe(200);
      const { permissions: _permissions, ...user } = response.json<
        User & { permissions: string[] }
      >();
      memberUser = user;
    });

    afterEach(async () => {
      await app?.close();
    });
    afterAll(async () => {
      if (pool) {
        try {
          await pool.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
        } finally {
          await pool.end();
        }
      }
    });

    async function login(email: string): Promise<Headers> {
      const response = await app.inject({
        method: "POST",
        url: "/api/auth/login",
        payload: { email, password },
      });
      expect(response.statusCode).toBe(200);
      expect(response.json()).toMatchObject({
        token_type: "Bearer",
        expires_in: 3600,
        access_token: expect.any(String),
      });
      return { authorization: `Bearer ${response.json().access_token}` };
    }

    async function grants(permissions: PermissionCode[], roleId = memberRole) {
      const response = await app.inject({
        method: "PUT",
        url: `/api/roles/${roleId}/permissions`,
        headers: admin,
        payload: { permissions },
      });
      expect(response.statusCode).toBe(200);
      expect(response.json()).toEqual({
        role_id: roleId,
        permissions: [...permissions].sort(),
      });
    }

    async function snapshot() {
      const result = await pool.query(`SELECT
      (SELECT jsonb_agg(r ORDER BY id) FROM roles r) AS roles,
      (SELECT jsonb_agg(u ORDER BY id) FROM users u) AS users,
      (SELECT jsonb_agg(c ORDER BY id) FROM credentials c) AS credentials,
      (SELECT jsonb_agg(p ORDER BY role_id, permission_code) FROM role_permissions p) AS grants`);
      return result.rows[0];
    }

    it("QA-01 creates and edits a profile with persisted grants and stable identity", async () => {
      const created = await app.inject({
        method: "POST",
        url: "/api/roles",
        headers: admin,
        payload: { name: "  Analista QA  ", description: "Consultas" },
      });
      expect(created.statusCode).toBe(201);
      const role = created.json<Role & { permissions: string[] }>();
      expect(role).toMatchObject({
        name: "Analista QA",
        description: "Consultas",
        permissions: [],
      });
      await grants(["users.read", "roles.read"], role.id);
      const edited = await app.inject({
        method: "PUT",
        url: `/api/roles/${role.id}`,
        headers: admin,
        payload: { name: "Analista sênior QA" },
      });
      expect(edited.statusCode).toBe(200);
      const expected = {
        ...role,
        name: "Analista sênior QA",
        description: null,
        permissions: ["roles.read", "users.read"],
      };
      expect(edited.json()).toEqual(expected);
      expect(
        (
          await app.inject({ url: `/api/roles/${role.id}`, headers: admin })
        ).json(),
      ).toEqual(expected);
      expect(
        (await app.inject({ url: "/api/roles", headers: admin })).json(),
      ).toContainEqual(expected);
      const stored = await pool.query(
        "SELECT name, description FROM roles WHERE id = $1",
        [role.id],
      );
      expect(stored.rows).toEqual([{ name: expected.name, description: null }]);
    });

    it("QA-02 grants, replaces and clears permissions for every user of a profile using existing sessions", async () => {
      for (const permissions of [
        [],
        ["users.read", "roles.read"],
        ["roles.read"],
        [],
      ] satisfies PermissionCode[][]) {
        await grants(permissions);
        for (const headers of [member, peer]) {
          const me = await app.inject({ url: "/api/auth/me", headers });
          expect(me.statusCode).toBe(200);
          expect(me.json().permissions).toEqual([...permissions].sort());
          for (const [path, permission] of [
            ["/api/users", "users.read"],
            ["/api/roles", "roles.read"],
          ] as const) {
            expect((await app.inject({ url: path, headers })).statusCode).toBe(
              permissions.includes(permission) ? 200 : 403,
            );
          }
        }
        const stored = await pool.query(
          "SELECT permission_code FROM role_permissions WHERE role_id = $1 ORDER BY permission_code",
          [memberRole],
        );
        expect(
          stored.rows.map(({ permission_code }) => permission_code),
        ).toEqual([...permissions].sort());
        expect(
          (await app.inject({ url: "/api/users", headers: admin })).statusCode,
        ).toBe(200);
      }
    });

    it("QA-03 moves a user between profiles through HTTP and immediately applies the new grants", async () => {
      await grants(["users.read"]);
      const created = await app.inject({
        method: "POST",
        url: "/api/roles",
        headers: admin,
        payload: { name: "Somente perfis QA" },
      });
      expect(created.statusCode).toBe(201);
      const newRole = created.json<Role>();
      await grants(["roles.read"], newRole.id);
      expect(
        (await app.inject({ url: "/api/users", headers: member })).statusCode,
      ).toBe(200);
      const moved = await app.inject({
        method: "PUT",
        url: `/api/users/${memberUser.id}`,
        headers: admin,
        payload: { name: memberUser.name, active: true, role_id: newRole.id },
      });
      expect(moved.statusCode).toBe(200);
      expect(moved.json()).toEqual({ ...memberUser, role_id: newRole.id });
      expect(
        (await app.inject({ url: "/api/users", headers: member })).statusCode,
      ).toBe(403);
      expect(
        (await app.inject({ url: "/api/roles", headers: member })).statusCode,
      ).toBe(200);
      expect(
        (await app.inject({ url: "/api/auth/me", headers: member })).json(),
      ).toMatchObject({ role_id: newRole.id, permissions: ["roles.read"] });
      expect(
        (await app.inject({ url: "/api/users", headers: peer })).statusCode,
      ).toBe(200);
    });

    it("QA-04 blocks and unblocks login and existing sessions without changing credentials, profile or peer access", async () => {
      await grants(["users.read"]);
      const initial = await snapshot();
      for (const active of [false, false, true, true]) {
        const updated = await app.inject({
          method: "PATCH",
          url: `/api/users/${memberUser.id}/access`,
          headers: admin,
          payload: { active },
        });
        expect(updated.statusCode).toBe(200);
        expect(updated.json()).toEqual({ ...memberUser, active });
        const stored = await snapshot();
        expect(stored).toEqual({
          ...initial,
          users: initial.users.map((user: User) =>
            user.id === memberUser.id ? { ...user, active } : user,
          ),
        });
        for (const path of ["/api/auth/me", "/api/users"]) {
          expect(
            (await app.inject({ url: path, headers: member })).statusCode,
          ).toBe(active ? 200 : 401);
        }
        expect(
          (await app.inject({ url: "/api/users", headers: peer })).statusCode,
        ).toBe(200);
        const attempt = await app.inject({
          method: "POST",
          url: "/api/auth/login",
          payload: { email: memberUser.email, password },
        });
        expect(attempt.statusCode).toBe(active ? 200 : 401);
        if (active) {
          expect(
            (
              await app.inject({
                url: "/api/users",
                headers: {
                  authorization: `Bearer ${attempt.json().access_token}`,
                },
              })
            ).statusCode,
          ).toBe(200);
        } else {
          expect(attempt.json()).toEqual({
            code: 401,
            message: "Invalid credentials or authentication token.",
            details: [],
          });
          expect(attempt.headers["set-cookie"]).toBeUndefined();
        }
      }
    });

    const operations = [
      {
        method: "POST",
        path: "/api/roles",
        payload: { name: "Criado QA" },
        permission: "roles.create",
        status: 201,
      },
      {
        method: "PUT",
        path: "/api/roles/:role",
        payload: { name: "Editado QA" },
        permission: "roles.update",
        status: 200,
      },
      {
        method: "GET",
        path: "/api/roles/:role",
        permission: "roles.read",
        status: 200,
      },
      {
        method: "GET",
        path: "/api/roles/:role/permissions",
        permission: "roles.read",
        status: 200,
      },
      {
        method: "GET",
        path: "/api/permissions",
        permission: "permissions.read",
        status: 200,
      },
      {
        method: "PUT",
        path: "/api/roles/:role/permissions",
        payload: { permissions: ["users.read"] },
        permission: "roles.permissions.update",
        status: 200,
      },
      {
        method: "PATCH",
        path: "/api/users/:user/access",
        payload: { active: false },
        permission: "users.update",
        status: 200,
      },
    ] as const;

    it.each(operations)(
      "QA-05 $method $path requires exactly $permission and denies unauthorized changes",
      async (operation) => {
        const request = {
          method: operation.method,
          url: operation.path
            .replace(":role", String(memberRole))
            .replace(":user", String(memberUser.id)),
          ...("payload" in operation ? { payload: operation.payload } : {}),
        };
        const initial = await snapshot();
        expect((await app.inject(request)).statusCode).toBe(401);
        // A profile called Administrador still has no implicit rights.
        const denied = await app.inject({ ...request, headers: member });
        expect(denied.statusCode).toBe(403);
        expect(denied.json()).toMatchObject({ code: 403, details: [] });
        expect(await snapshot()).toEqual(initial);
        // An unrelated permission cannot authorize this action either.
        await grants(["users.read"]);
        const withReadOnly = await snapshot();
        expect(
          (await app.inject({ ...request, headers: member })).statusCode,
        ).toBe(403);
        expect(await snapshot()).toEqual(withReadOnly);
        await grants([operation.permission]);
        const allowed = await app.inject({ ...request, headers: member });
        expect(allowed.statusCode).toBe(operation.status);
      },
    );

    it("QA-06 rejects privilege escalation and self-unblocking by a blocked user without side effects", async () => {
      await grants([
        "roles.create",
        "roles.update",
        "roles.read",
        "permissions.read",
        "roles.permissions.update",
        "users.update",
      ]);
      const blocked = await app.inject({
        method: "PATCH",
        url: `/api/users/${memberUser.id}/access`,
        headers: admin,
        payload: { active: false },
      });
      expect(blocked.statusCode).toBe(200);
      const initial = await snapshot();
      for (const operation of operations) {
        const response = await app.inject({
          method: operation.method,
          url: operation.path
            .replace(":role", String(memberRole))
            .replace(":user", String(memberUser.id)),
          headers: member,
          ...("payload" in operation ? { payload: operation.payload } : {}),
        });
        expect(
          response.statusCode,
          `${operation.method} ${operation.path}`,
        ).toBe(401);
      }
      expect(
        (
          await app.inject({
            method: "PATCH",
            url: `/api/users/${memberUser.id}/access`,
            headers: member,
            payload: { active: true },
          })
        ).statusCode,
      ).toBe(401);
      expect(await snapshot()).toEqual(initial);
    });

    it.each([
      { permissions: ["users.read", "unknown.permission"] },
      { permissions: ["users.read", "users.read"] },
      { permissions: null },
    ])(
      "QA-07 rejects invalid grants atomically and keeps existing sessions authorized: %j",
      async (payload) => {
        await grants(["users.read"]);
        const initial = await snapshot();
        const rejected = await app.inject({
          method: "PUT",
          url: `/api/roles/${memberRole}/permissions`,
          headers: admin,
          payload,
        });
        expect(rejected.statusCode).toBe(400);
        expect(await snapshot()).toEqual(initial);
        expect(
          (await app.inject({ url: "/api/users", headers: member })).statusCode,
        ).toBe(200);
      },
    );

    it("QA-08 rejects duplicate profile names on creation and editing without losing grants", async () => {
      await grants(["users.read"]);
      const initial = await snapshot();
      for (const method of ["POST", "PUT"] as const) {
        const response = await app.inject({
          method,
          url: method === "POST" ? "/api/roles" : `/api/roles/${memberRole}`,
          headers: admin,
          payload: { name: "  Operador QA  " },
        });
        expect(response.statusCode).toBe(409);
        expect(response.json()).toEqual({
          code: 409,
          message: "A role with this name already exists.",
          details: [],
        });
        expect(await snapshot()).toEqual(initial);
      }
      expect(
        (await app.inject({ url: "/api/users", headers: member })).statusCode,
      ).toBe(200);
    });
  },
);
