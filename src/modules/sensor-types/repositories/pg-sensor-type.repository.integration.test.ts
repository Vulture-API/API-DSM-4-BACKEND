import { Pool } from "pg";
import { afterAll, beforeAll, beforeEach, describe, expect, it } from "vitest";

import { PgSensorTypeRepository } from "@/modules/sensor-types/repositories/sensor-type.repository.js";

// Roda só quando TEST_DATABASE_URL aponta para um Postgres descartável (o CI
// sobe um). Usa um schema próprio, apagado no fim: nunca toca tabelas reais.
const TEST_DATABASE_URL = process.env.TEST_DATABASE_URL;
const SCHEMA = `it_sensor_types_${process.pid}`;

describe.skipIf(!TEST_DATABASE_URL)(
  "PgSensorTypeRepository (Postgres real)",
  () => {
    let pool: Pool;
    let repository: PgSensorTypeRepository;

    beforeAll(async () => {
      const admin = new Pool({ connectionString: TEST_DATABASE_URL });
      await admin.query(`DROP SCHEMA IF EXISTS ${SCHEMA} CASCADE`);
      await admin.query(`CREATE SCHEMA ${SCHEMA}`);
      await admin.query(`
      CREATE TABLE ${SCHEMA}.sensor_types (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name varchar(50) NOT NULL UNIQUE,
        unit_of_measure varchar(20) NOT NULL,
        factor numeric NULL,
        gain numeric NULL,
        offset_value numeric NULL
      );
    `);
      await admin.end();

      pool = new Pool({
        connectionString: TEST_DATABASE_URL,
        options: `-c search_path=${SCHEMA}`,
      });
      repository = new PgSensorTypeRepository(pool);
    });

    beforeEach(async () => {
      await pool.query("TRUNCATE sensor_types RESTART IDENTITY");
    });

    afterAll(async () => {
      await pool?.query(`DROP SCHEMA IF EXISTS ${SCHEMA} CASCADE`);
      await pool?.end();
    });

    it("should_create_find_update_and_delete", async () => {
      const created = await repository.create({
        name: "Temperatura",
        unit_of_measure: "°C",
      });
      expect(created).toEqual({
        id: 1,
        name: "Temperatura",
        unit_of_measure: "°C",
        factor: null,
        gain: null,
        offset_value: null,
      });

      expect(await repository.findById(1)).toEqual(created);
      expect(await repository.findByName("temperatura")).toEqual(created);
      expect(await repository.findAll()).toEqual([created]);

      const updated = await repository.update(1, { unit_of_measure: "K" });
      expect(updated).toMatchObject({
        name: "Temperatura",
        unit_of_measure: "K",
      });
      expect(await repository.update(99, { name: "X" })).toBeNull();

      expect(await repository.delete(1)).toBe(true);
      expect(await repository.delete(1)).toBe(false);
      expect(await repository.findById(1)).toBeNull();
    });

    it("should_store_keep_and_remove_the_calibration", async () => {
      const created = await repository.create({
        name: "Luminosidade",
        unit_of_measure: "lux",
        factor: 3.6,
        gain: 0.000805860805,
        offset_value: -12.5,
      });
      expect(created).toMatchObject({
        factor: 3.6,
        gain: 0.000805860805,
        offset_value: -12.5,
      });

      const kept = await repository.update(created.id, { name: "Luz" });
      expect(kept).toMatchObject({
        name: "Luz",
        factor: 3.6,
        gain: 0.000805860805,
        offset_value: -12.5,
      });

      const cleared = await repository.update(created.id, {
        gain: null,
        offset_value: null,
      });
      expect(cleared).toMatchObject({
        factor: 3.6,
        gain: null,
        offset_value: null,
      });
      expect(await repository.findById(created.id)).toEqual(cleared);
    });
  },
);
