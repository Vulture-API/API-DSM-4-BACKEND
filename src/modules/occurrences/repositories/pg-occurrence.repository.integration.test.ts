// Usa os parsers do bootstrap real, inclusive timestamp sem fuso como UTC.
import "@/config/database.js";

import { Pool, types } from "pg";
import { afterAll, beforeAll, describe, expect, it } from "vitest";

import { PgOccurrenceRepository } from "@/modules/occurrences/repositories/pg-occurrence.repository.js";

// Roda só com TEST_DATABASE_URL (o CI sobe um Postgres), num schema próprio.
const TEST_DATABASE_URL = process.env.TEST_DATABASE_URL;
const SCHEMA = `it_occurrences_${process.pid}`;

types.setTypeParser(types.builtins.INT8, (value) => Number(value));

describe.skipIf(!TEST_DATABASE_URL)(
  "PgOccurrenceRepository (Postgres real)",
  () => {
    let pool: Pool;
    let repository: PgOccurrenceRepository;
    const at = new Date("2026-10-14T12:00:00.000Z");

    beforeAll(async () => {
      const admin = new Pool({ connectionString: TEST_DATABASE_URL });
      await admin.query(`DROP SCHEMA IF EXISTS ${SCHEMA} CASCADE`);
      await admin.query(`CREATE SCHEMA ${SCHEMA}`);
      // Mesmas colunas, checks e índices da migration 016 do BANCO.
      await admin.query(`
        SET search_path = ${SCHEMA};
        CREATE TABLE stations (
          id int PRIMARY KEY, name text NOT NULL,
          last_communication_at timestamp, created_at timestamp NOT NULL
        );
        CREATE TABLE sensor_types (id int PRIMARY KEY, name text);
        CREATE TABLE sensors (
          id int PRIMARY KEY, station_id int REFERENCES stations (id),
          sensor_type_id int REFERENCES sensor_types (id), local_identifier text,
          min_value decimal(10,2), max_value decimal(10,2)
        );
        CREATE TABLE readings (
          id bigserial PRIMARY KEY, sensor_id int, value decimal(10,2),
          unix_time bigint, data_consistent boolean NOT NULL DEFAULT true
        );
        CREATE TABLE processing_checkpoints (
          key varchar(100) PRIMARY KEY, value varchar(100) NOT NULL,
          updated_at timestamp NOT NULL DEFAULT current_timestamp
        );
        CREATE TABLE occurrences (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          type varchar(30) NOT NULL, status varchar(10) NOT NULL DEFAULT 'OPEN',
          station_id int NOT NULL REFERENCES stations (id) ON DELETE CASCADE,
          sensor_id int REFERENCES sensors (id) ON DELETE CASCADE,
          reading_id bigint, value decimal(10,2), description varchar(255) NOT NULL,
          detected_at timestamp NOT NULL, resolved_at timestamp,
          CHECK ((status = 'OPEN') = (resolved_at IS NULL))
        );
        CREATE UNIQUE INDEX ON occurrences (station_id)
          WHERE type = 'COMMUNICATION_FAILURE' AND status = 'OPEN';
        CREATE UNIQUE INDEX ON occurrences (sensor_id)
          WHERE type = 'OUT_OF_RANGE' AND status = 'OPEN';
        INSERT INTO stations VALUES
          (1, 'Norte', '2026-10-14 11:00:00', '2026-01-01 00:00:00'),
          (2, 'Sul', NULL, '2026-10-01 00:00:00');
        INSERT INTO sensor_types VALUES (1, 'Temperatura');
        INSERT INTO sensors VALUES (10, 1, 1, 'temp', -10, 50), (11, 1, 1, 'umid', NULL, NULL);
        INSERT INTO readings (sensor_id, value, unix_time, data_consistent) VALUES
          (10, 20, 1790000001, true), (10, 70.5, 1790000002, true),
          (11, 999, 1790000003, false);
      `);
      await admin.end();
      // Fuso da sessão diferente de UTC: as datas não podem deslocar.
      pool = new Pool({
        connectionString: TEST_DATABASE_URL,
        options: `-c search_path=${SCHEMA} -c TimeZone=America/Sao_Paulo`,
      });
      repository = new PgOccurrenceRepository(pool);
    });

    afterAll(async () => {
      await pool?.query(`DROP SCHEMA IF EXISTS ${SCHEMA} CASCADE`);
      await pool?.end();
    });

    it("lê a última comunicação das estações em UTC", async () => {
      expect(await repository.listStationCommunications()).toEqual([
        {
          station_id: 1,
          station_name: "Norte",
          last_communication_at: new Date("2026-10-14T11:00:00Z"),
          created_at: new Date("2026-01-01T00:00:00Z"),
        },
        {
          station_id: 2,
          station_name: "Sul",
          last_communication_at: null,
          created_at: new Date("2026-10-01T00:00:00Z"),
        },
      ]);
    });

    it("abre uma falha por estação e resolve as abertas", async () => {
      const failure = { station_id: 2, description: "calada", detected_at: at };
      expect(await repository.openCommunicationFailure(failure)).toBe(true);
      expect(await repository.openCommunicationFailure(failure)).toBe(false);

      const open = await repository.listOpenCommunicationFailures();
      expect(open).toEqual([{ id: expect.any(Number), station_id: 2 }]);
      expect(await repository.findById(open[0]!.id)).toMatchObject({
        type: "COMMUNICATION_FAILURE",
        station_name: "Sul",
        sensor_id: null,
        detected_at: at.toISOString(),
      });

      expect(await repository.resolveOccurrences([open[0]!.id], at)).toBe(1);
      expect(await repository.resolveOccurrences([open[0]!.id], at)).toBe(0);
      expect(await repository.listOpenCommunicationFailures()).toEqual([]);
    });

    it("lê leituras com limites, marca fora da faixa e avança checkpoint", async () => {
      expect(await repository.getCheckpoint()).toBe(0);
      const readings = await repository.findReadingsAfter(0, 10);
      expect(readings.map((r) => r.reading_id)).toEqual([1, 2, 3]);
      expect(readings[1]).toEqual({
        reading_id: 2,
        sensor_id: 10,
        station_id: 1,
        sensor_identifier: "temp",
        value: 70.5,
        unix_time: 1790000002,
        data_consistent: true,
        min_value: -10,
        max_value: 50,
      });
      expect(readings[2]).toMatchObject({ min_value: null, max_value: null });
      expect(await repository.findReadingsAfter(2, 10)).toHaveLength(1);

      const flag = {
        station_id: 1,
        sensor_id: 10,
        reading_id: 2,
        reading_unix_time: 1790000002,
        value: 70.5,
        description: "acima",
        detected_at: at,
      };
      expect(await repository.flagOutOfRange(flag)).toBe(true);
      expect(await repository.flagOutOfRange(flag)).toBe(false);
      const consistent = await pool.query(
        "SELECT data_consistent FROM readings WHERE id = 2",
      );
      expect(consistent.rows[0].data_consistent).toBe(false);

      await repository.setCheckpoint(3);
      await repository.setCheckpoint(3);
      expect(await repository.getCheckpoint()).toBe(3);
    });

    it("desfaz a marcação se a ocorrência não puder ser gravada", async () => {
      await expect(
        repository.flagOutOfRange({
          station_id: 999,
          sensor_id: 11,
          reading_id: 1,
          reading_unix_time: 1790000001,
          value: 20,
          description: "x",
          detected_at: at,
        }),
      ).rejects.toMatchObject({ code: "23503" });
      const reading = await pool.query(
        "SELECT data_consistent FROM readings WHERE id = 1",
      );
      expect(reading.rows[0].data_consistent).toBe(true);
    });

    it("lista com joins, filtros, período e paginação e resolve", async () => {
      const all = await repository.list({ page: 1, limit: 20 });
      expect(all.meta).toEqual({
        total_records: 2,
        total_pages: 1,
        current_page: 1,
      });
      const outOfRange = await repository.list({
        page: 1,
        limit: 20,
        type: "OUT_OF_RANGE",
        status: "OPEN",
        station_id: 1,
        sensor_id: 10,
        from: new Date("2026-10-14T11:59:00Z"),
        to: new Date("2026-10-14T12:00:00Z"),
      });
      expect(outOfRange.data).toEqual([
        {
          id: expect.any(Number),
          type: "OUT_OF_RANGE",
          status: "OPEN",
          station_id: 1,
          station_name: "Norte",
          sensor_id: 10,
          sensor_identifier: "temp",
          sensor_type: "Temperatura",
          reading_id: 2,
          value: 70.5,
          description: "acima",
          detected_at: at.toISOString(),
          resolved_at: null,
        },
      ]);
      expect(
        (
          await repository.list({
            page: 1,
            limit: 20,
            from: new Date("2026-10-14T12:00:01Z"),
          })
        ).data,
      ).toEqual([]);
      const second = await repository.list({ page: 2, limit: 1 });
      expect(second.data).toHaveLength(1);
      expect(second.meta.total_pages).toBe(2);

      const id = outOfRange.data[0]!.id;
      expect(await repository.resolve(id, at)).toMatchObject({
        status: "RESOLVED",
        resolved_at: at.toISOString(),
      });
      expect(await repository.resolve(id, at)).toBeNull();
      expect(await repository.findById(999)).toBeNull();
    });
  },
);
